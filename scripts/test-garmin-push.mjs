import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../supabase/functions/garmin-activity-push/index.ts',import.meta.url),'utf8');
let handler, requests=[], tasks=[];
const secret='test-only-'.repeat(4);
const env={GARMIN_PUSH_SECRET:secret,SUPABASE_URL:'https://test.invalid',SUPABASE_SERVICE_ROLE_KEY:'test-admin',GARMIN_CLIENT_ID:'test-client'};
let fetcher=async()=>[];
const context=vm.createContext({TextEncoder,Response,Request,URL,AbortSignal,Date,JSON,
  Deno:{env:{get:k=>env[k]},serve:fn=>{handler=fn}},EdgeRuntime:{waitUntil:p=>tasks.push(p)},
  fetch:async(url,init)=>{requests.push({url,init});return new Response(JSON.stringify(await fetcher(url,init)),{headers:{'Content-Type':'application/json'}});}});
vm.runInContext(source,context);
const detail={userId:'user',summaryId:'summary',activityId:42,summary:{activityType:'RUNNING',startTimeInSeconds:1700000000,startTimeOffsetInSeconds:32400,distanceInMeters:5000},samples:[null,{latitudeInDegree:35,longitudeInDegree:139},{latitudeInDegree:35.1,longitudeInDegree:139.1}]};
context.detail=detail;
const record=vm.runInContext('parsed(detail)',context);
assert.equal(record.source_external_id,'garmin-api:42');
assert.equal(record.route.length,2);
assert.equal(record.distance_km,5);
context.record=record;
context.existing=[{distance_km:5,started_at:new Date(1700000000000+3600000).toISOString(),source:'strava'}];
assert.equal(vm.runInContext('duplicate(existing,record)',context),false,'separate runs on same day survive');
context.existing[0].started_at=record.started_at;
assert.equal(vm.runInContext('duplicate(existing,record)',context),true,'matching Strava run deduplicated');
context.existing=[{source_external_id:'garmin-api:99',distance_km:5,started_at:record.started_at}];
assert.equal(vm.runInContext('duplicate(existing,record)',context),false,'distinct Garmin activity IDs survive');
assert.equal((await handler(new Request('https://test.invalid/wrong',{method:'POST',body:'{}'}))).status,404);
assert.equal((await handler(new Request('https://test.invalid/drain',{method:'POST'}))).status,403);
assert.equal(requests.length,0);
context.bad={activityDetails:[detail,{}]};
await assert.rejects(vm.runInContext('enqueue(bad)',context));
assert.equal(requests.length,0,'invalid batch performs no partial inserts');
fetcher=async(url)=>url.includes('state=in.')?[{id:1,user_id:'owner',payload:detail,attempts:0}]:url.includes('id=eq.1&state=')?[{id:1}]:[];
await vm.runInContext('drain()',context);
assert.ok(requests.some(r=>r.init.method==='PATCH'&&JSON.parse(r.init.body).state==='ignored'));
assert.ok(!requests.some(r=>r.url.endsWith('/runs')),'disconnected owner cannot import queued data');
requests=[];
fetcher=async()=>{throw Error('database unavailable');};
assert.equal((await handler(new Request('https://test.invalid/drain',{method:'POST',headers:{Authorization:'Bearer test-admin'}}))).status,503);
assert.equal((await handler(new Request('https://test.invalid/'+secret,{method:'POST',body:JSON.stringify({activityDetails:[detail]})}))).status,503,'failed durable receipt requests Garmin retry');
await Promise.all(tasks);
console.log('Garmin Push mock tests passed (parsing, deduplication, auth, batch validation, disconnect, database failure).');
