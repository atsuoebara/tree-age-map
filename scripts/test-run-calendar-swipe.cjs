'use strict';
const fs=require('node:fs');
const assert=require('node:assert/strict');
const html=fs.readFileSync(require('node:path').join(__dirname,'../index.html'),'utf8');
const start=html.indexOf('function rrCalShiftMonth(delta){');
const end=html.indexOf("document.getElementById('rrRunCalendarYear').onchange",start);
assert.ok(start>=0&&end>start,'swipe module exists');
const code=html.slice(start,end);
assert.doesNotThrow(()=>new Function(code),'swipe code syntax');
const events={};
let now={id:'runner'};
let currentUser=now,rrCalOwner='runner',rrCalMode='calendar',rrCalYear=2026,rrCalMonth=10,rrCalDay=3,renderCount=0;
const grid={addEventListener:(event,callback,opts)=>{assert.ok(opts,'touch listener options');events[event]=callback}};
const touch=t=>({touches:[t],changedTouches:[t],preventDefault(){this.prevented=true}});
const module=new Function('rrCalGrid','currentUser','rrCalOwner','rrCalMode','rrCalYear','rrCalMonth','rrCalDay','rrCalRender',code+';return {get:()=>[rrCalYear,rrCalMonth,rrCalDay],shift:rrCalShiftMonth}');
let api=module(grid,currentUser,rrCalOwner,rrCalMode,rrCalYear,rrCalMonth,rrCalDay,()=>renderCount++);
function gesture(dx,dy){const a={clientX:150,clientY:150},b={clientX:150+dx,clientY:150+dy};events.touchstart(touch(a));const e={changedTouches:[b],preventDefault(){this.prevented=true}};events.touchend(e);return e.prevented===true;}
assert.equal(gesture(-100,10),true,'left swipe accepted');
assert.deepEqual(api.get(),[2026,11,null],'left means next month');
assert.equal(gesture(100,5),true,'right swipe accepted');
assert.deepEqual(api.get(),[2026,10,null],'right means previous month');
assert.equal(gesture(20,5),false,'short drag must keep day taps');
assert.equal(gesture(-90,95),false,'vertical scroll remains native');
assert.deepEqual(api.get(),[2026,10,null]);
assert.equal(gesture(-80,25),true);
assert.deepEqual(api.get(),[2026,11,null]);
api.shift(1);assert.deepEqual(api.get(),[2027,0,null],'cross year forward');
api.shift(-1);assert.deepEqual(api.get(),[2026,11,null],'cross year backwards');
assert.equal(html.includes("id=\"cloudRunsList\""),true,'original list intact');
assert.equal(html.includes("data-rr-run-mode=\"list\""),true,'original list tab intact');
assert.equal(html.includes("function rrCalDate(row)"),true,'original date safety intact');
assert.equal(html.includes("today-dedupe-01"),true,'Today fix intact');
assert.equal(html.includes("p0-breakdown-01"),true,'A-4 intact');
assert.equal(html.includes("align-self:stretch"),true,'mobile card alignment intact');
console.log('calendar swipe gesture and year rollover checks PASS');
