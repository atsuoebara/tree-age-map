import assert from 'node:assert/strict';
import { createHandler } from '../supabase/functions/garmin-oauth/index.ts';
const base = 'https://example.supabase.co/functions/v1/garmin-oauth';
const origin = 'https://runnersrings.com';
const values = { SUPABASE_URL: 'https://example.supabase.co', SUPABASE_SERVICE_ROLE_KEY: 'test', GARMIN_CLIENT_ID: 'client', GARMIN_CLIENT_SECRET: 'secret', GARMIN_TOKEN_KEY: 'ab'.repeat(32) };
let calls = [], stored;
const mock = async (url, init = {}) => {
  calls.push([url, init]);
  if (url.endsWith('/auth/v1/user')) return Response.json({ id: 'user-1' });
  if (url.includes('/oauth/token')) return Response.json({ access_token: 'private-access', refresh_token: 'private-refresh', expires_in: 86400 });
  if (url.endsWith('/user/id')) return Response.json({ userId: 'garmin-1' });
  if (url.endsWith('/user/permissions')) return Response.json(['ACTIVITY_EXPORT']);
  if (url.includes('/rest/v1/garmin_api_connections') && init.method === 'POST') { stored = JSON.parse(init.body); return Response.json([stored]); }
  throw new Error('Unexpected request');
};
const handler = createHandler(k => values[k], mock);
const empty = createHandler(() => undefined, mock);
assert.equal((await empty(new Request(base + '/callback'))).status, 400);
assert.equal((await empty(new Request(base + '/callback?code=x&state=y'))).status, 503);
assert.equal((await handler(new Request(base + '/start', { method: 'POST' }))).status, 403);
const logo = await handler(new Request(base + '/logo.png'));
assert.equal(logo.headers.get('content-type'), 'image/png');
const png = Buffer.from(await logo.arrayBuffer());
assert.equal(png.readUInt32BE(16), 300); assert.equal(png.readUInt32BE(20), 300);
const form = new URLSearchParams({ access_token: 'user-jwt' });
const start = await handler(new Request(base + '/start', { method: 'POST', headers: { Origin: origin }, body: form }));
assert.equal(start.status, 303);
const auth = new URL(start.headers.get('location'));
assert.equal(auth.origin, 'https://connect.garmin.com');
assert.equal(auth.searchParams.get('redirect_uri'), base + '/callback');
assert.equal(auth.searchParams.get('code_challenge_method'), 'S256');
const cookie = start.headers.get('set-cookie').split(';')[0];
assert.ok(start.headers.get('set-cookie').includes('HttpOnly; Secure; SameSite=Lax'));
assert.ok(!cookie.includes('user-1'));
const cb = (state, extra = 'code=one-time-code', ck = cookie) => handler(new Request(`${base}/callback?${extra}&state=${state}`, { headers: { Cookie: ck } }));
const before = calls.length;
assert.equal((await cb('wrong')).status, 400);
assert.equal((await cb(auth.searchParams.get('state'), 'error=access_denied')).status, 400);
assert.equal((await cb(auth.searchParams.get('state'), undefined, cookie + 'tampered')).status, 400);
assert.equal(calls.length, before);
const realNow = Date.now;
Date.now = () => realNow() + 601000;
assert.equal((await cb(auth.searchParams.get('state'))).status, 400);
Date.now = realNow;
const result = await cb(auth.searchParams.get('state'));
assert.equal(result.status, 303);
assert.equal(result.headers.get('location'), origin + '/?garmin=connected');
assert.ok(result.headers.get('set-cookie').includes('Max-Age=0'));
assert.equal(stored.user_id, 'user-1');
assert.ok(!stored.tokens_ciphertext.includes('private-access'));
const tokenCall = calls.find(([url]) => url.includes('/oauth/token'));
const verifier = tokenCall[1].body.get('code_verifier');
const challenge = Buffer.from(await crypto.subtle.digest('SHA-256', new TextEncoder().encode(verifier))).toString('base64url');
assert.equal(challenge, auth.searchParams.get('code_challenge'));
assert.equal(tokenCall[1].body.get('redirect_uri'), base + '/callback');
assert.ok(calls.every(([url]) => !url.includes('strava') && !url.includes('/garmin_connections')));
const revokeCalls = [];
const disconnect = createHandler(k => values[k], async (url, init = {}) => {
  revokeCalls.push([url, init]);
  if (url.endsWith('/auth/v1/user')) return Response.json({ id: 'user-1' });
  if (url.includes('select=tokens_ciphertext')) return Response.json([stored]);
  if (url.endsWith('/user/registration')) return new Response(null, { status: 204 });
  if (init.method === 'DELETE' && url.includes('/garmin_api_connections')) return Response.json([]);
  throw new Error('Unexpected disconnect request');
});
const removed = await disconnect(new Request(base + '/disconnect', { method: 'POST', headers: { Origin: origin }, body: new URLSearchParams({ access_token: 'user-jwt' }) }));
assert.equal(removed.status, 303);
assert.equal(removed.headers.get('location'), origin + '/?garmin=disconnected');
assert.equal(revokeCalls.at(-2)[0], 'https://apis.garmin.com/wellness-api/rest/user/registration');
assert.equal(revokeCalls.at(-2)[1].headers.Authorization, 'Bearer private-access');
assert.equal(revokeCalls.at(-1)[1].method, 'DELETE');
const statusHandler = createHandler(k => values[k], async (url, init) => {
  if (url.endsWith('/auth/v1/user')) return Response.json({ id: 'user-1' });
  assert.ok(url.endsWith('user_id=eq.user-1&select=user_id'));
  return Response.json([{user_id:'user-1'}]);
});
const status = await statusHandler(new Request(base + '/status', { method: 'POST', headers: { Origin: origin }, body: new URLSearchParams({access_token:'user-jwt'}) }));
assert.deepEqual(await status.json(), {connected:true});
assert.equal(status.headers.get('access-control-allow-origin'), origin);
assert.equal((await statusHandler(new Request(base + '/status', {method:'POST', headers:{Origin:'https://other.example'},body:new URLSearchParams({access_token:'user-jwt'})}))).status,403);
console.log('Garmin OAuth: config guard, origin, PKCE, cookie, state, denial, tampering, token encryption, callback and logo checks passed.');
