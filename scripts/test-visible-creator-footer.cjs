#!/usr/bin/env node
'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const {spawnSync}=require('node:child_process');
const nav=fs.readFileSync('rr-site-nav.js','utf8');
const index=fs.readFileSync('index.html','utf8');
const sw=fs.readFileSync('sw.js','utf8');
const result=spawnSync(process.execPath,['--check','rr-site-nav.js'],{encoding:'utf8'});
assert.equal(result.status,0,result.stderr);
assert(nav.includes("footer.id='rrGlobalFooter'"),'visible common footer absent');
assert(nav.includes('footerInner.append(footerBrand,footerLinks,supportLink,coffeeLink,ofuseLink,creatorCredit)'),'support and credit must be in the actual visible common footer');
assert(nav.includes("supportLink.href='https://buy.stripe.com/eVqbJ38UAa4JaMU0r53ks00'"),'existing Stripe support URL must remain');
assert(nav.includes("supportLink.className='rrSupportLink'"),'visible supporter CTA missing');
assert(nav.includes("dropdown.replaceChildren(...links.map(x=>makeLink(x,en)),makeMenuSupportLink(en),makeCoffeeLink(en),makeOfuseLink(en))"),'menu support link must be rendered in mobile dropdown');
assert(nav.includes("a.className='rrNavSupportLink'"),'menu support link class absent');
assert(nav.includes("a.href='https://buy.stripe.com/eVqbJ38UAa4JaMU0r53ks00'"),'menu URL must match existing Stripe link');
assert(nav.includes("a.target='_blank';a.rel='noopener noreferrer'"),'menu Stripe external link safety attributes missing');
assert(nav.includes("en?'♡ Support Runner\\'s Rings':'♡ Runner\\'s Ringsを応援する'"),'menu support bilingual copy missing');
assert(nav.includes("Support Runner\\'s Rings") && nav.includes("Runner\\'s Ringsを応援する"),'bilingual support CTA missing');
assert(nav.includes("footerLinks.replaceChildren(...footerItems.map(x=>makeLink(x,en)))"),'retain common navigation links');
assert(nav.includes('creatorCredit.className=\'rrCreatorCredit\''),'credit class missing');
assert(nav.includes("creatorLink.href='https://www.instagram.com/atsuoebarun/'"),'expected Instagram absent');
assert(nav.includes("creatorLink.rel='noopener noreferrer'"),'safe external link missing');
assert(nav.includes("creatorLabel.textContent=en?'Made by':'作っている人'"),'bilingual visible creator missing');
assert(nav.includes("creatorAccount.textContent=en?' (personal account)':'（個人アカウント）'"),'personal account must translate');
assert(nav.includes('creatorLink.setAttribute(\'aria-label\',en?'),'aria label must translate');
assert(nav.includes("coffeeLink.href='https://buymeacoffee.com/runnersrings'"),'Coffee footer URL missing');
assert(nav.includes("a.href='https://buymeacoffee.com/runnersrings'"),'Coffee mobile URL missing');
assert(nav.includes("footerInner.append(footerBrand,footerLinks,supportLink,coffeeLink,ofuseLink,creatorCredit)"),'Coffee link not rendered');
assert(nav.includes("ofuseLink.href='https://ofuse.me/runnersrings'"),'OFUSE footer URL missing');
assert(nav.includes("a.href='https://ofuse.me/runnersrings'"),'OFUSE mobile URL missing');
assert(nav.includes('makeOfuseLink(en)'),'OFUSE not in mobile dropdown');
assert(nav.includes("ofuseLink.textContent=en?'✉ Support via OFUSE':'✉ OFUSEで応援'"),'OFUSE bilingual footer missing');
assert(nav.includes("ofuseLink.target='_blank';ofuseLink.rel='noopener noreferrer'"),'OFUSE safe external link attributes missing');
assert(index.includes('/rr-site-nav.js?v=20261111-ofuse-support-01'),'navigation asset URL not bumped');
const a=index.match(/const APP_BUILD = '([^']+)'/)?.[1], b=sw.match(/const RR_BUILD = '([^']+)'/)?.[1];
assert.equal(a,b,'index and service worker builds differ');
assert.match(a,/^\d{4}\.\d{2}\.\d{2}\.\d+$/,'valid app build expected');
assert(a>='2026.11.11.02','app build must not predate OFUSE footer release');
assert(nav.includes("body > footer:not(#rrGlobalFooter),main > footer:not(#rrGlobalFooter){display:none!important}"),'test must ensure legacy footer is hidden, so actual link location matters');
console.log('Visible global footer Instagram regression: passed');
