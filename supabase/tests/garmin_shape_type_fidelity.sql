 OR NOT NEW.import_enabled OR NOT (NEW.permissions @> '["ACTIVITY_EXPORT"]'::jsonb) THEN
   DELETE FROM probe_type.probe_result WHERE user_id=OLD.user_id;
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER purge_connection BEFORE DELETE OR UPDATE OF connection_version,import_enabled,permissions
ON probe_type.garmin_connection FOR EACH ROW EXECUTE FUNCTION probe_type.purge_connection();
