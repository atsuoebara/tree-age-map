CREATE FUNCTION probe_type.probe_guard() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
BEGIN
 IF NOT EXISTS (
   SELECT 1 FROM probe_type.run r
   JOIN probe_type.garmin_connection c ON c.user_id=r.user_id
   JOIN probe_type.inbox i ON i.id=NEW.inbox_id AND i.user_id=r.user_id
   WHERE r.id=NEW.run_id AND r.user_id=NEW.user_id
   AND r.deleted_at IS NULL AND r.source='garmin'
   AND r.source_external_id LIKE 'garmin-api:%'
   AND length(r.source_external_id)>length('garmin-api:')
   AND r.started_at IS NOT NULL
   AND c.import_enabled AND c.permissions @> '["ACTIVITY_EXPORT"]'::jsonb
   AND c.connection_version=NEW.connection_version
   AND i.connection_version=NEW.connection_version
 ) THEN
   RAISE EXCEPTION 'unowned_or_stale_garmin_run';
 END IF;
 RETURN NEW;
END $$;
CREATE TRIGGER probe_guard BEFORE INSERT OR UPDATE ON probe_type.probe_result
FOR EACH ROW EXECUTE FUNCTION probe_type.probe_guard();
CREATE FUNCTION probe_type.purge_connection() RETURNS trigger
LANGUAGE plpgsql SECURITY INVOKER SET search_path='' AS $$
BEGIN
