-- Garmin Connect Push inbox; separate from existing Connect IQ tables.
create table if not exists public.garmin_activity_inbox (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  garmin_user_id text not null,
  summary_id text not null,
  payload jsonb not null,
  state text not null default 'pending' check (state in ('pending','processing','saved','duplicate','ignored','retry')),
  attempts integer not null default 0,
  next_retry_at timestamptz not null default now(),
  last_error text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, summary_id)
);
create index if not exists garmin_activity_inbox_pending_idx on public.garmin_activity_inbox(next_retry_at) where state in ('pending','retry');
alter table public.garmin_activity_inbox enable row level security;
revoke all on public.garmin_activity_inbox from public, anon, authenticated;
grant select, insert, update, delete on public.garmin_activity_inbox to service_role;
grant usage, select on sequence public.garmin_activity_inbox_id_seq to service_role;
-- Idempotency for the new Garmin API records, without modifying old Connect IQ records.
create unique index if not exists runs_garmin_api_external_id_unique
on public.runs(user_id, source_external_id)
where source = 'garmin' and source_external_id is not null;
