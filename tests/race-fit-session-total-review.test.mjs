import assert from 'node:assert/strict';
import {Encoder,Decoder,Stream} from '../fit-sdk/src/index.js';
import {reviewFitSessionRecordTotals as review} from '../src/race-fit-session-total-review.mjs';
const at=s=>new Date(Date.UTC(2026,10,3,0,0,s));
const opts={userConfirmedFile:true,privateView:true,confirmRunning:true,sourceProvenance:'user_uploaded_fit'};
const records=[{timestamp:at(0),distance:0},{timestamp:at(60),distance:500},{timestamp:at(120),distance:1000}];
const msg=(totalDistance=1000)=>({sessionMesgs:[{sport:'running',startTime:at(0),timestamp:at(120),totalDistance}],recordMesgs:records});
const good=review(msg(),opts);
assert.equal(good.status,'diagnostic_only');
assert.deepEqual(good.flags,[]);
assert.equal(good.recordDistanceM,1000);
assert.equal(good.sessionTotalDistanceM,1000);
assert.equal(good.clockElapsedSeconds,120);
for(const key of ['qualityCertified','analysisAllowed','writeAllowed','providerDataCombined'])assert.equal(good[key],false);
const mismatch=review(msg(1400),opts);
assert.ok(mismatch.flags.includes('session_vs_last_record_distance_mismatch'));
assert.ok(review(msg(1008),opts).flags.length===0,'minor encoding rounding is not a reason to invent an offset');
assert.ok(review(msg(undefined),opts).flags.length===0,'explicit default parameter is 1000');
assert.ok(review({sessionMesgs:[{...msg().sessionMesgs[0],totalDistance:null}],recordMesgs:records},opts).flags.includes('session_total_distance_missing'));
assert.ok(review({...msg(),recordMesgs:[{...records[0],distance:10},records[1],records[2]]},opts).flags.includes('record_distance_origin_nonzero'));
assert.ok(review({...msg(),recordMesgs:[{...records[0],timestamp:at(10)},records[1],records[2]]},opts).flags.includes('first_record_delayed'));
assert.ok(review({...msg(),sessionMesgs:[{...msg().sessionMesgs[0],timestamp:at(20)}]},opts).flags.includes('record_after_session_end'));
assert.ok(review({...msg(),sessionMesgs:[{...msg().sessionMesgs[0],timestamp:at(300)}]},opts).flags.includes('last_record_far_before_session_end'));
assert.equal(review({...msg(),sessionMesgs:[{...msg().sessionMesgs[0],totalDistance:-5}]},opts).reason,'session_total_distance_invalid');
assert.equal(review({...msg(),recordMesgs:[records[0],{...records[2],distance:-1}]},opts).status,'blocked');
assert.equal(review(msg(),{...opts,userConfirmedFile:false}).status,'blocked');
assert.equal(review(msg(),{...opts,sourceProvenance:'strava_stream'}).status,'blocked');
assert.equal(review(msg(),{...opts,privateView:false}).status,'blocked');
assert.equal(review({...msg(),sessionMesgs:[...msg().sessionMesgs,...msg().sessionMesgs]},opts).status,'blocked');
const enc=new Encoder();
enc.writeMesg({mesgNum:18,sport:'running',startTime:at(0),timestamp:at(120),totalDistance:1200});
for(const r of records)enc.writeMesg({mesgNum:20,...r});
const binary=enc.close(),buffer=binary.buffer.slice(binary.byteOffset,binary.byteOffset+binary.byteLength);
const decoder=new Decoder(Stream.fromArrayBuffer(buffer));
assert.equal(decoder.isFIT(),true);
const {messages,errors}=decoder.read();
assert.deepEqual(errors,[]);
const actual=review(messages,opts);
assert.equal(actual.status,'diagnostic_only');
assert.ok(actual.flags.includes('session_vs_last_record_distance_mismatch'),'generated binary round-trip must retain session distance mismatch');
assert.equal(actual.qualityCertified,false);
assert.equal(actual.writeAllowed,false);
console.log('FIT session-vs-record consistency diagnostic PASS: synthetic and binary mismatch, provenance and read-only safety');
