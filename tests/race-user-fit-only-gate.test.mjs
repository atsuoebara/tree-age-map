import assert from 'node:assert/strict';
import {assessOwnFitForOfflineReview as assess} from '../src/race-user-fit-only-gate.mjs';
const records=[{elapsedS:0,distanceM:0,heartRate:130,cadence:83,power:188},{elapsedS:295,distanceM:1000,heartRate:150,cadence:87,power:250}];
const base={userConfirmedFile:true,privateView:true,sourceProvenance:'user_uploaded_fit',session:{sport:'running'},confirmRunning:true,records};
const good=assess(base);
assert.equal(good.status,'offline_shape_review');
assert.equal(good.source,'user_fit_only');
assert.equal(good.writeAllowed,false);
assert.equal(good.analysisAllowed,false);
assert.equal(good.providerDataCombined,false);
assert.deepEqual(good.availableSensors,['heartRate','cadence','power']);
const missing=assess({...base,records:records.map(({elapsedS,distanceM})=>({elapsedS,distanceM}))});
assert.deepEqual(missing.missingSensors,['heartRate','cadence','power']);
assert.equal(assess({...base,userConfirmedFile:false}).reason,'owner_confirmation_or_private_view_missing');
assert.equal(assess({...base,privateView:false}).status,'blocked');
assert.equal(assess({...base,sourceProvenance:'strava_stream'}).reason,'not_a_user_provided_fit');
assert.equal(assess({...base,sourceProvenance:'garmin_api'}).reason,'not_a_user_provided_fit');
assert.equal(assess({...base,session:{sport:'cycling'}}).reason,'running_not_verified');
assert.equal(assess({...base,confirmRunning:false}).status,'blocked');
assert.equal(assess({...base,records:[records[0]]}).reason,'record_count_invalid');
assert.equal(assess({...base,records:[records[0],{elapsedS:0,distanceM:1000}]}).reason,'record_order_invalid');
assert.equal(assess({...base,records:[records[0],{elapsedS:295,distanceM:-10}]}).reason,'record_order_invalid');
assert.equal(assess({...base,records:[records[0],{elapsedS:295,distanceM:0}]}).reason,'no_measured_distance_progress');
assert.equal(assess({...base,records:[records[0],{elapsedS:295,distanceM:1000,heartRate:NaN}]}).reason,'sensor_value_invalid');
assert.equal(assess({...base,records:[records[0],{elapsedS:295,distanceM:1000,power:0}]}).status,'offline_shape_review','zero watts may be valid');
assert.deepEqual(records[0],{elapsedS:0,distanceM:0,heartRate:130,cadence:83,power:188});
console.log('FIT-only offline review PASS: synthetic owner confirmation, running-only, monotonic samples, missing sensors, provenance separation; no writes');
