import assert from 'node:assert/strict';
import {Decoder,Stream} from '../fit-sdk/src/index.js';
import {makeSyntheticRaceFit} from '../scripts/make-synthetic-race-fit.mjs';
import {reviewSingleUserFitBuffer} from '../src/race-fit-local-file-review.mjs';
const opts={confirmedOwner:true,confirmedRace:true};
const bytes=makeSyntheticRaceFit();
assert.ok(bytes instanceof ArrayBuffer);
assert.ok(bytes.byteLength>16&&bytes.byteLength<16000000);
const decoder=new Decoder(Stream.fromArrayBuffer(bytes));
assert.equal(decoder.isFIT(),true);
assert.equal(decoder.checkIntegrity(),true);
const {messages,errors}=decoder.read();
assert.deepEqual(errors,[]);
assert.equal(messages.sessionMesgs.length,1);
assert.equal(messages.sessionMesgs[0].sport,'running');
assert.equal(messages.sessionMesgs[0].totalDistance,5000);
assert.equal(messages.recordMesgs.at(-1).distance,5000);
assert.equal(messages.recordMesgs[0].distance,0);
assert.equal(messages.recordMesgs.length,26);
assert.equal(messages.recordMesgs.some(x=>x.positionLat!=null||x.positionLong!=null),false);
assert.equal(messages.recordMesgs.some(x=>x.heartRate!=null||x.cadence!=null||x.power!=null),false);
const actual=reviewSingleUserFitBuffer(bytes,opts);
assert.equal(actual.status,'candidate_unverified',JSON.stringify(actual));
assert.equal(actual.distanceM,5000);
assert.equal(actual.clockElapsedS,1620);
assert.deepEqual(actual.segments.map(x=>Math.round(x.clockElapsedS)),[315,318,320,324,343]);
assert.ok(actual.flags.includes('no_timer_events'),'absence of timer hints must be displayed as unknown');
assert.equal(actual.qualityCertified,false);
assert.equal(actual.analysisAllowed,false);
assert.equal(actual.writeAllowed,false);
assert.equal(actual.providerDataCombined,false);
assert.equal(reviewSingleUserFitBuffer(bytes,{...opts,confirmedOwner:false}).status,'blocked');
assert.equal(reviewSingleUserFitBuffer(bytes,{...opts,confirmedRace:false}).status,'blocked');
console.log('Privacy-safe 5km synthetic FIT fixture PASS: SDK roundtrip, expected clock splits, no GPS/sensors/personal data, no writes.');
