import assert from 'node:assert/strict';
import {Encoder,Decoder,Stream} from '../fit-sdk/src/index.js';
import {reviewFitClockAnomalies as review} from '../src/race-fit-clock-anomaly-review.mjs';
const start=new Date('2026-11-03T00:00:00Z');
const at=n=>new Date(start.getTime()+n*1000);
const options={userConfirmedFile:true,privateView:true,confirmRunning:true,sourceProvenance:'user_uploaded_fit'};
const messages=records=>({sessionMesgs:[{sport:'running',startTime:start}],recordMesgs:records});
const normal=[{timestamp:at(0),distance:0},{timestamp:at(60),distance:200},{timestamp:at(120),distance:400}];
const good=review(messages(normal),options);
assert.equal(good.status,'diagnostic_only');
assert.equal(good.strictProbeStatus,'synthetic_candidate_only');
assert.deepEqual(good.flags,[]);
assert.equal(good.qualityCertified,false);
assert.equal(good.writeAllowed,false);
const late=review(messages([{timestamp:at(5),distance:0},{timestamp:at(65),distance:200}]),options);
assert.equal(late.strictProbeStatus,'blocked');
assert.equal(late.strictProbeReason,'record_and_session_start_must_match');
assert.ok(late.flags.includes('first_record_delayed_clock_unknown'));
assert.equal(late.firstRecordDelayS,5);
const origin=review(messages([{timestamp:at(0),distance:12},{timestamp:at(60),distance:300}]),options);
assert.ok(origin.flags.includes('first_distance_nonzero_origin_unknown'));
assert.equal(origin.strictProbeReason,'cumulative_distance_origin_not_zero');
const gap=review(messages([{timestamp:at(0),distance:0},{timestamp:at(180),distance:200},{timestamp:at(240),distance:400}]),options);
assert.ok(gap.flags.includes('long_record_clock_gap'));
assert.equal(gap.qualityCertified,false);
const plateau=review(messages([{timestamp:at(0),distance:0},{timestamp:at(60),distance:0},{timestamp:at(120),distance:200}]),options);
assert.ok(plateau.flags.includes('distance_plateau_cause_unknown'));
const timer=review({...messages(normal),eventMesgs:[{event:'timer',eventType:'stop'},{event:'timer',eventType:'start'}]},options);
assert.ok(timer.flags.includes('timer_event_present_verify_pause'));
assert.equal(timer.analysisAllowed,false);
assert.equal(review(messages([{timestamp:at(0),distance:0},{distance:200}]),options).reason,'record_timestamp_missing');
assert.equal(review(messages([{timestamp:at(0),distance:0},{timestamp:at(0),distance:200}]),options).reason,'timestamp_not_strictly_increasing');
assert.equal(review(messages([{timestamp:at(0),distance:0},{timestamp:at(60),distance:-1}]),options).reason,'distance_invalid');
assert.equal(review(messages([{timestamp:at(0),distance:100},{timestamp:at(60),distance:50}]),options).reason,'distance_reversal');
assert.equal(review(messages(normal),{...options,sourceProvenance:'strava_stream'}).status,'blocked');
// Generate genuine FIT binary with the bundled SDK, exercising decoder Date shapes.
const enc=new Encoder();
enc.writeMesg({mesgNum:18,sport:'running',startTime:start,totalDistance:400});
for(const r of [{timestamp:at(7),distance:0},{timestamp:at(187),distance:200},{timestamp:at(247),distance:400}])
 enc.writeMesg({mesgNum:20,...r});
const bytes=enc.close(),buf=bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength);
const dec=new Decoder(Stream.fromArrayBuffer(buf));
assert.equal(dec.isFIT(),true);
const {messages:realShape,errors}=dec.read();
assert.deepEqual(errors,[]);
const actual=review(realShape,options);
assert.equal(actual.status,'diagnostic_only');
assert.ok(actual.flags.includes('first_record_delayed_clock_unknown'));
assert.ok(actual.flags.includes('long_record_clock_gap'));
assert.equal(actual.strictProbeStatus,'blocked');
assert.equal(actual.analysisAllowed,false);
console.log('FIT first-sample delay, pause signal, missing timestamp, sparse sample guards PASS; generated binary decoded, no inference or writes');
