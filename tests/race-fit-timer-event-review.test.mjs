import assert from 'node:assert/strict';
import {Encoder,Decoder,Stream} from '../fit-sdk/src/index.js';
import {inspectFitTimerEvents as inspect} from '../src/race-fit-timer-event-review.mjs';
import {normalizeDecodedFitForOfflineProbe as split} from '../src/race-fit-sdk-isolated-adapter.mjs';
const start=new Date('2026-11-03T00:00:00Z'),at=s=>new Date(start.getTime()+s*1000);
const opts={userConfirmedFile:true,privateView:true,confirmRunning:true,sourceProvenance:'user_uploaded_fit'};
const records=[{timestamp:at(0),distance:0},{timestamp:at(200),distance:500},{timestamp:at(260),distance:1000}];
const messages=(eventMesgs,rs=records)=>({sessionMesgs:[{sport:'running',startTime:start}],recordMesgs:rs,eventMesgs});
const check=events=>inspect(messages(events),opts);
const paused=check([{event:'timer',eventType:'start',timestamp:at(0)},{event:'timer',eventType:'stop',timestamp:at(100)},{event:'timer',eventType:'start',timestamp:at(160)}]);
assert.equal(paused.status,'diagnostic_only');
assert.equal(paused.clockElapsedSeconds,260,'do not subtract 60 sec stop');
assert.deepEqual(paused.observedStopIntervals,[{startOffsetSeconds:100,endOffsetSeconds:160,durationSeconds:60}]);
assert.equal(paused.movingTimeCalculated,false);
assert.equal(paused.qualityCertified,false);
assert.equal(paused.analysisAllowed,false);
assert.equal(paused.writeAllowed,false);
assert.equal(paused.providerDataCombined,false);
const splitResult=split(messages([]),opts);
assert.equal(splitResult.status,'synthetic_candidate_only');
assert.equal(splitResult.segments[0].clockElapsedS,260,'legacy clock-based split must NOT use pause events or make moving-pace claims');
assert.equal(check(undefined).reason,'timer_events_absent_cannot_assume_continuous');
assert.ok(check([]).flags.includes('no_timer_events'));
assert.equal(check([{event:'timer',eventType:'stop'}]).reason,'timer_event_timestamp_missing');
assert.equal(check([{event:'timer',eventType:'stop',timestamp:at(-1)}]).reason,'timer_event_outside_record_bounds');
assert.equal(check([{event:'timer',eventType:'stop',timestamp:at(10)},{event:'timer',eventType:'start',timestamp:at(9)}]).reason,'timer_event_time_reversed');
assert.ok(check([{event:'timer',eventType:'stop',timestamp:at(100)}]).flags.includes('unmatched_stop_event'));
assert.ok(check([{event:'timer',eventType:'start',timestamp:at(50)}]).flags.includes('start_without_prior_stop'));
assert.ok(check([{event:'timer',eventType:'stop',timestamp:at(50)},{event:'timer',eventType:'stop',timestamp:at(70)},{event:'timer',eventType:'start',timestamp:at(80)}]).flags.includes('duplicate_stop_event'));
assert.ok(check([{event:'timer',eventType:'stop',timestamp:at(30)},{event:'timer',eventType:'start',timestamp:at(30)}]).flags.includes('zero_duration_stop_interval'));
assert.ok(check([{event:'timer',eventType:'pause',timestamp:at(60)}]).flags.includes('unknown_timer_event_type'));
assert.equal(inspect(messages([]),{...opts,sourceProvenance:'strava_stream'}).status,'blocked');
assert.equal(inspect(messages([]),{...opts,userConfirmedFile:false}).status,'blocked');
assert.equal(inspect(messages([]),{...opts,privateView:false}).status,'blocked');
// FIT binary: bundled official SDK writes a timer stop/start message pair,
// then bundled decoder parses them as Date and event enumerations.
const encoder=new Encoder();
encoder.writeMesg({mesgNum:18,sport:'running',startTime:start,totalDistance:1000});
encoder.writeMesg({mesgNum:20,...records[0]});
encoder.writeMesg({mesgNum:21,event:'timer',eventType:'stop',timestamp:at(100)});
encoder.writeMesg({mesgNum:21,event:'timer',eventType:'start',timestamp:at(160)});
encoder.writeMesg({mesgNum:20,...records[1]});
encoder.writeMesg({mesgNum:20,...records[2]});
const bytes=encoder.close(),buffer=bytes.buffer.slice(bytes.byteOffset,bytes.byteOffset+bytes.byteLength);
const decoder=new Decoder(Stream.fromArrayBuffer(buffer));
assert.equal(decoder.isFIT(),true);
const {messages:decoded,errors}=decoder.read();
assert.deepEqual(errors,[]);
const checked=inspect(decoded,opts);
assert.equal(checked.clockElapsedSeconds,260);
assert.deepEqual(checked.observedStopIntervals,[{startOffsetSeconds:100,endOffsetSeconds:160,durationSeconds:60}]);
assert.equal(checked.movingTimeCalculated,false);
assert.equal(checked.writeAllowed,false);
assert.equal(split(decoded,opts).segments[0].clockElapsedS,260);
console.log('FIT timer event synthetic and FIT binary round-trip PASS: stops not subtracted, incomplete events blocked/flagged; no moving-time claim or writes');
