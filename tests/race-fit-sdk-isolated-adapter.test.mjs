import assert from 'node:assert/strict';
import {Encoder} from '../fit-sdk/src/index.js';
import {decodeAthleteFitArrayBufferForOfflineProbe as decode,normalizeDecodedFitForOfflineProbe as normalize} from '../src/race-fit-sdk-isolated-adapter.mjs';
const start=new Date('2026-11-03T00:00:00.000Z');
const options={userConfirmedFile:true,privateView:true,confirmRunning:true,sourceProvenance:'user_uploaded_fit'};
const records=Array.from({length:11},(_,i)=>({timestamp:new Date(start.getTime()+i*60000),distance:i*200,heartRate:120+i,cadence:80+i,power:200+i}));
const sample={sessionMesgs:[{sport:'running',startTime:start}],recordMesgs:records};
const normalized=normalize(sample,options);
assert.equal(normalized.status,'synthetic_candidate_only');
assert.deepEqual(normalized.segments.map(x=>x.clockElapsedS),[300,300]);
assert.equal(normalized.writeAllowed,false);
assert.equal(normalized.analysisAllowed,false);
assert.equal(normalized.providerDataCombined,false);
// Exercise the actual repository Garmin FIT encoder and decoder, with a
// generated binary fixture (NOT an athlete's record).
const encoder=new Encoder();
encoder.writeMesg({mesgNum:18,sport:'running',startTime:start,totalDistance:2000});
for(const row of records)encoder.writeMesg({mesgNum:20,...row});
const binary=encoder.close();
const bytes=binary.buffer.slice(binary.byteOffset,binary.byteOffset+binary.byteLength);
const parsed=decode(bytes,options);
assert.equal(parsed.status,'synthetic_candidate_only',JSON.stringify(parsed));
assert.deepEqual(parsed.segments.map(x=>x.clockElapsedS),[300,300]);
assert.equal(parsed.qualityCertified,false);
assert.equal(parsed.analysisAllowed,false);
assert.equal(parsed.writeAllowed,false);
assert.equal(decode(bytes,{...options,userConfirmedFile:false}).status,'blocked');
assert.equal(decode(bytes,{...options,sourceProvenance:'strava_stream'}).status,'blocked');
assert.equal(decode(new Uint8Array([0,1,2,3]).buffer,options).status,'blocked');
assert.equal(normalize({...sample,recordMesgs:records.map((r,i)=>i===0?{...r,distance:9}:r)},options).reason,'cumulative_distance_origin_not_zero');
assert.equal(normalize({...sample,recordMesgs:records.map((r,i)=>i===0?{...r,timestamp:new Date(start.getTime()+1000)}:r)},options).reason,'record_and_session_start_must_match');
assert.equal(normalize({...sample,sessionMesgs:[...sample.sessionMesgs,...sample.sessionMesgs]},options).status,'blocked');
assert.equal(normalize({...sample,recordMesgs:records.map((r,i)=>i===2?{...r,distance:NaN}:r)},options).status,'blocked');
assert.equal(normalize({...sample,sessionMesgs:[{sport:'cycling',startTime:start}]},options).status,'blocked');
assert.deepEqual(records[0],{timestamp:start,distance:0,heartRate:120,cadence:80,power:200},'decoder/adapter must not mutate fixture');
console.log('Generated binary FIT SDK round-trip and isolated 1km bridge PASS, no live file or production writes');
