'use strict';
const assert=require('node:assert/strict');
const {checkElapsedQuality,mapSummaryToTrainingInput}=require('../src/race-elapsed-quality-gate-review.cjs');
const {suggestTraining}=require('../src/race-training-suggestions.cjs');
const proof=()=>({version:'race-continuity-proof-v0-synthetic',fromOriginalSamples:true,samplesInSegment:7,maxDistanceGapM:180,maxClockGapS:60});
const make=(elapsed=[300,300,300,360,360,360],tail=false)=>{
 const segments=elapsed.map((clock_elapsed_s,i)=>({segment_index:i+1,distance_m:1000,clock_elapsed_s,quality_flags:[],elapsed_continuity_evidence:proof()}));
 if(tail)segments.push({segment_index:7,distance_m:420,clock_elapsed_s:188,quality_flags:['partial_segment'],elapsed_continuity_evidence:proof()});
 return {analysis_version:'garmin-activity-details-v1',distance_basis:'device_cumulative_m',time_basis:'clock_elapsed_seconds',quality_flags:[],excluded_samples:0,segments};
};
const fresh=make();
assert.equal(checkElapsedQuality(fresh,fresh.segments[0],0).elapsedQualityOk,true);
const out=suggestTraining(mapSummaryToTrainingInput(fresh));
assert.equal(out.status,'ok');assert.equal(out.reason,'later_splits_slower');
assert.deepEqual(out.recommendations.map(x=>x.id),['long_easy','even_pace']);
const withTail=make(undefined,true);
assert.equal(suggestTraining(mapSummaryToTrainingInput(withTail)).reason,'later_splits_slower');
assert.equal(mapSummaryToTrainingInput(withTail).splits[6].distanceKm,.42);
const checkFailure=(name,change)=>{
 const d=make();change(d);const x=suggestTraining(mapSummaryToTrainingInput(d));
 assert.equal(x.status,'insufficient_data',name);
};
checkFailure('real shape lacking continuity evidence',d=>{for(const s of d.segments)delete s.elapsed_continuity_evidence});
checkFailure('unverified overall flag',d=>d.quality_flags.push('plateau_or_equal_time'));
checkFailure('unknown overall flag',d=>d.quality_flags.push('future_unrecognized'));
checkFailure('one excluded sample',d=>d.excluded_samples=1);
checkFailure('missing exclusion metadata',d=>delete d.excluded_samples);
checkFailure('time basis mismatch',d=>d.time_basis='moving_time');
checkFailure('distance gap excessive',d=>d.segments[2].elapsed_continuity_evidence.maxDistanceGapM=251);
checkFailure('clock gap excessive',d=>d.segments[2].elapsed_continuity_evidence.maxClockGapS=121);
checkFailure('sparse samples',d=>d.segments[2].elapsed_continuity_evidence.samplesInSegment=2);
checkFailure('missing evidence provenance',d=>d.segments[2].elapsed_continuity_evidence.fromOriginalSamples=false);
checkFailure('unexpected proof format',d=>d.segments[2].elapsed_continuity_evidence.version='real-unsupported');
checkFailure('partial non-terminal',d=>{d.segments[2].distance_m=420;d.segments[2].quality_flags=['partial_segment']});
checkFailure('sensor coverage not elapsed signal',d=>{d.segments[2].elapsed_continuity_evidence=null;d.segments[2].quality_flags=['sensor_missing']});
checkFailure('unrecognized segment flag',d=>d.segments[2].quality_flags=['gps_jump']);
checkFailure('not exact full 1km',d=>d.segments[2].distance_m=999.5);
checkFailure('bad elapsed',d=>d.segments[2].clock_elapsed_s=0);
const sensor=make();sensor.segments[1].quality_flags=['sensor_missing'];
assert.equal(suggestTraining(mapSummaryToTrainingInput(sensor)).status,'ok','sensor missing alone must not invalidate elapsed');
const low=make([300,300,300,300,300]);assert.equal(suggestTraining(mapSummaryToTrainingInput(low)).status,'insufficient_data');
assert.equal(suggestTraining(mapSummaryToTrainingInput(null)).status,'insufficient_data');
console.log('Synthetic-only elapsed quality gate tests passed');
