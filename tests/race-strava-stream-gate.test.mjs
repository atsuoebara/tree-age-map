import assert from 'node:assert/strict';
import {checkStravaStreamShape as check} from '../src/race-strava-stream-gate.mjs';
const base={ownerVerified:true,explicitConsent:true,scope:['activity:read'],visibility:'everyone'};
const sample={time:{data:[0,200,400]},distance:{data:[0,650,1290]},heartrate:{data:[120,145,156]},cadence:{data:[80,84,89]},watts:{data:[180,220,240]}};
const ok=check({...base,streams:sample});
assert.equal(ok.status,'shape_only');
assert.deepEqual(ok.technicalFields,['time','distance','heartrate','cadence','watts']);
assert.equal(ok.sampleCount,3);
assert.equal(ok.analysisAllowed,false);
assert.equal(ok.fetchAllowed,false);
assert.equal(ok.storageAllowed,false);
assert.equal(check({...base,policyApproval:true,streams:sample}).analysisAllowed,false);
const noSensors=check({...base,streams:{time:sample.time,distance:sample.distance}});
assert.equal(noSensors.status,'shape_only');
assert.deepEqual(noSensors.missingFields,['heartrate','cadence','watts']);
assert.equal(check({...base,streams:sample,visibility:'only_me'}).reason,'required_scope_missing');
assert.equal(check({...base,streams:sample,visibility:'only_me',scope:['activity:read','activity:read_all']}).requiredScope,'activity:read_all');
assert.equal(check({...base,streams:sample,ownerVerified:false}).reason,'owner_or_consent_missing');
assert.equal(check({...base,streams:sample,explicitConsent:false}).reason,'owner_or_consent_missing');
assert.equal(check({...base,streams:{time:sample.time}}).reason,'distance_time_missing');
assert.equal(check({...base,streams:{time:sample.time,distance:{data:[0,100]}}}).reason,'sample_lengths_mismatch');
assert.equal(check({...base,streams:{time:{data:[0,0,10]},distance:sample.distance}}).reason,'non_monotonic_distance_or_time');
assert.equal(check({...base,streams:{time:sample.time,distance:{data:[0,650,600]}}}).reason,'non_monotonic_distance_or_time');
assert.equal(check({...base,streams:{...sample,heartrate:{data:[120,null,150]}}}).reason,'invalid_stream_data');
assert.equal(check({...base,streams:{...sample,watts:{data:[150,200]}}}).reason,'sample_lengths_mismatch');
assert.deepEqual(sample.time.data,[0,200,400], 'synthetic originals remain unchanged');
console.log('Strava synthetic streams gate PASS: scope, missing sensors, monotonicity, matching counts; analysis/storage/fetch remain disabled');
