import assert from 'node:assert/strict';
import {States,initialConsent,transitionConsent} from '../src/garmin-consent-lifecycle-contract.mjs';
const A='owner-A',B='owner-B',v1='gen-old',v2='gen-new';
const action=(record,type,generation=v1,owner=A)=>transitionConsent(record,{type,generation,owner});
const pass=(record,type,generation=v1)=>{const r=action(record,type,generation);assert.equal(r.ok,true,type+':'+r.reason);return r.record;};
let a=initialConsent(A,v1),b=initialConsent(B,'gen-B');
assert.equal(a.canImport,true);
assert.equal(action(a,'disconnect',v1,B).ok,false);
a=pass(a,'disconnect');
assert.equal(a.state,States.DISCONNECT_REQUESTED);
assert.equal(a.canImport,false);
a=pass(a,'begin_revoke');
assert.equal(a.state,States.REVOKE_INFLIGHT);
a=pass(a,'reauthorize',v2);
assert.equal(a.generation,v1,'old generation controls remote revoke');
assert.equal(a.pendingGeneration,v2);
assert.equal(a.canImport,false,'new consent not active while old DELETE is pending');
a=pass(a,'revoke_timeout');
assert.equal(a.state,States.REVOKE_UNKNOWN);
assert.equal(a.pendingGeneration,v2,'timeout must retain pending consent intent, not activate it');
assert.equal(action(a,'revoke_confirmed','some-other-generation').ok,false);
assert.equal(a.canImport,false);
a=pass(a,'retry_revoke');
assert.equal(a.state,States.REVOKE_INFLIGHT);
a=pass(a,'revoke_confirmed');
assert.equal(a.state,States.DISCONNECTED);
assert.equal(a.pendingGeneration,null,'do not silently activate a possibly revoked new grant');
assert.equal(a.canImport,false);
assert.equal(action(a,'revoke_confirmed').ok,false);
assert.equal(action(a,'retry_revoke').ok,false);
a=pass(a,'reauthorize',v2);
assert.equal(a.state,States.CONNECTED);
assert.equal(a.generation,v2);
assert.equal(a.canImport,true,'explicit new grant after confirmed old revoke may connect');
assert.equal(action(a,'disconnect',v1).ok,false,'stale disconnect fails closed');
assert.equal(action(a,'begin_revoke',v1).ok,false);
assert.equal(b.state,States.CONNECTED);
assert.equal(b.canImport,true,'other owner unaffected');
// Remote result first, reauthorization second.
let c=pass(pass(pass(initialConsent(A,v1),'disconnect'),'begin_revoke'),'revoke_confirmed');
c=pass(c,'reauthorize',v2);
assert.equal(c.state,States.CONNECTED);
assert.equal(c.canImport,true);
// A second reauth during unknown outcome stays inert.
let d=pass(pass(initialConsent(A,v1),'disconnect'),'begin_revoke');
d=pass(d,'revoke_timeout');
d=pass(d,'reauthorize',v2);
assert.equal(d.state,States.REVOKE_UNKNOWN);
assert.equal(d.canImport,false);
assert.equal(d.pendingGeneration,v2);
// No remote error or unrecognized event ever implicitly grants consent.
assert.equal(action(d,'garmin_503').ok,false);
assert.equal(action(d,'revoke_timeout').ok,false);
assert.throws(()=>initialConsent(A,''),/required/);
console.log('Garmin consent lifecycle isolated PASS: midflight reauth held, unknown outcome fail-closed, old-generation fences, safe explicit reconnect.');
